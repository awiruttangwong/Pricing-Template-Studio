  function buildOilBands(start, end) {
    return Array.from({ length: end - start + 1 }, (_, index) => {
      const min = start + index;
      return {
        id: `b${index + 1}`,
        label: buildBandLabel(min),
        min,
        max: Number((min + 0.99).toFixed(2)),
      };
    });
  }

